/**
 * Smart image resolver based on item.image, item.imageUrl, food name (title), category, and food type
 */
export const getFoodImageUrl = (item = {}) => {
  // 1️⃣ Direct image URL from DB if provided (supports both image and imageUrl)
  const explicitImage = item.image || item.imageUrl;
  if (explicitImage && typeof explicitImage === 'string' && explicitImage.trim().startsWith('http')) {
    return explicitImage.trim();
  }

  const title = (item.title || item.foodName || '').toLowerCase().trim();
  const category = item.category || 'Cooked Meals';
  const foodType = item.foodType || 'Veg';

  if (!title) {
    const catConfig = CATEGORY_FALLBACK_IMAGES[category] || CATEGORY_FALLBACK_IMAGES.Other;
    return catConfig[foodType] || catConfig.default || CATEGORY_FALLBACK_IMAGES.Other.default;
  }

  // 2️⃣ Check centralized foodImages mapping (longest key match first)
  const mapKeys = Object.keys(foodImages).sort((a, b) => b.length - a.length);
  for (const key of mapKeys) {
    if (title.includes(key)) {
      return foodImages[key];
    }
  }

  // 3️⃣ Check preset tags
  const titleWords = title.split(/\s+/);
  const matchedPreset = FOOD_IMAGE_PRESETS.find((preset) =>
    preset.tags.some((tag) => title.includes(tag.toLowerCase()) || titleWords.includes(tag.toLowerCase()))
  );
  if (matchedPreset) {
    return matchedPreset.url;
  }

  // 4️⃣ Category + foodType fallback images
  const catConfig = CATEGORY_FALLBACK_IMAGES[category] || CATEGORY_FALLBACK_IMAGES.Other;
  return catConfig[foodType] || catConfig.default || CATEGORY_FALLBACK_IMAGES.Other.default;
};
